import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../../docs/brand/tokens/", import.meta.url);
const source = JSON.parse(await readFile(new URL("tokens.json", root), "utf8"));
const check = process.argv.includes("--check");

function flatten(value, prefix = "") {
  return Object.entries(value).flatMap(([key, item]) => {
    const name = prefix ? `${prefix}.${key}` : key;
    return typeof item === "object"
      ? flatten(item, name)
      : [[name, String(item)]];
  });
}

const primitives = new Map(flatten(source.primitives));
const cssName = (key) => `--holon-${key.replaceAll(".", "-")}`;

function reference(value, asCss) {
  if (!value.startsWith("{")) {
    return asCss && /^#[\da-f]{6}$/i.test(value) ? value.toLowerCase() : value;
  }
  const key = value.slice(1, -1);
  const raw = primitives.get(key);
  if (raw === undefined) throw new Error(`Unknown token: ${key}`);
  return asCss ? `var(${cssName(key)})` : raw;
}

function declarations(entries) {
  return entries
    .map(([key, value]) => `  ${cssName(key)}: ${reference(value, true)};`)
    .join("\n");
}

const css = [
  "/* Generated by tooling/brand/tokens.mjs. Edit tokens.json. */",
  ":root {",
  declarations([...primitives]),
  "}",
  "",
  ...Object.entries(source.themes).flatMap(([theme, aliases]) => [
    `${theme === "light" ? ":root,\n" : ""}[data-holon-theme="${theme}"] {`,
    `  color-scheme: ${theme};`,
    declarations(Object.entries(aliases)),
    "}",
    "",
  ]),
].join("\n");

function luminance(hex) {
  if (!/^#[\da-f]{6}$/i.test(hex)) throw new Error(`Expected RGB hex: ${hex}`);
  const channels = [1, 3, 5].map((offset) => {
    const value = Number.parseInt(hex.slice(offset, offset + 2), 16) / 255;
    return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  });
  return channels[0] * 0.2126 + channels[1] * 0.7152 + channels[2] * 0.0722;
}

const report = [];
for (const [theme, aliases] of Object.entries(source.themes)) {
  const pairs = [
    ...["bg-page", "bg-surface", "bg-subtle"].flatMap((background) =>
      ["text-primary", "text-secondary", "text-muted", "link"].map(
        (foreground) => [foreground, background, 4.5],
      ),
    ),
    ...["action-bg", "action-hover", "action-pressed"].map((background) => [
      "action-fg",
      background,
      4.5,
    ]),
    ["selected-fg", "selected-bg", 4.5],
    ["focus", "bg-page", 3],
    ["focus", "bg-surface", 3],
    ["border-control", "bg-surface", 3],
    ...["success", "warning", "danger", "info"].map((status) => [
      `${status}-fg`,
      `${status}-bg`,
      4.5,
    ]),
  ];
  for (const [foreground, background, minimum] of pairs) {
    const fg = reference(aliases[foreground], false);
    const bg = reference(aliases[background], false);
    const values = [luminance(fg), luminance(bg)].toSorted((a, b) => b - a);
    const ratio = (values[0] + 0.05) / (values[1] + 0.05);
    if (ratio < minimum) {
      throw new Error(`${theme}: ${foreground}/${background}: ${ratio}`);
    }
    report.push({ theme, foreground, background, ratio, minimum });
  }
}

for (const [name, body] of [
  ["tokens.css", css],
  ["contrast-report.json", `${JSON.stringify(report, null, 2)}\n`],
]) {
  const destination = new URL(name, root);
  if (check) {
    if ((await readFile(destination, "utf8")) !== body) {
      throw new Error(
        `${name} differs from tokens.json; run pnpm brand:generate`,
      );
    }
  } else {
    await writeFile(destination, body);
  }
}
console.log(
  `Holon brand: ${report.length} contrast pairs passed; tokens ${check ? "checked" : "generated"}.`,
);
